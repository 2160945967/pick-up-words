// Build-time: precompile Vue templates in index.html into render functions,
// so the app can use the runtime-only Vue build under strict CSP (no unsafe-eval).
const fs = require('fs');
const path = require('path');
const { compile } = require('@vue/compiler-dom');

const ROOT = path.resolve(__dirname, '..');
const INDEX = path.join(ROOT, 'index.html');
const OUT = path.join(ROOT, 'src', 'vue-renders.ts');

const html = fs.readFileSync(INDEX, 'utf8');

// Extract <script type="text/x-template" id="..."> ... </script>
const re = /<script[^>]*type="text\/x-template"[^>]*id="([^"]+)"[^>]*>([\s\S]*?)<\/script>/g;
const templates = {};
let m;
while ((m = re.exec(html)) !== null) {
  templates[m[1]] = m[2];
}

const idToName = {
  'errorbook-vue-template': 'errorbookRender',
  'favorites-vue-template': 'favoritesRender',
  'wordbook-vue-template': 'wordbookRender',
};

const out = [];
out.push('// AUTO-GENERATED by tools/compile-vue-templates.cjs — do not edit.');
out.push('// Precompiled Vue render functions (runtime-only build, CSP-safe: no unsafe-eval).');
out.push('');
out.push('/* eslint-disable */');
out.push('declare const Vue: any;');
out.push('');

for (const [id, exportName] of Object.entries(idToName)) {
  const tpl = templates[id];
  if (tpl == null) {
    throw new Error(`template ${id} not found in index.html`);
  }
  const { code } = compile(tpl, {
    mode: 'function',
    prefixIdentifiers: true,
    hoistStatic: true,
  });
  // `code` is a function body that sets up hoisted nodes and `return`s the render fn.
  // Defer the setup (and the global `Vue` access) until the first render, so importing
  // this module in a test environment without Vue does not throw.
  out.push(`let _${exportName}: any = null;`);
  out.push(`export const ${exportName} = function(_ctx: any, _cache: any) {`);
  out.push(`  if (!_${exportName}) { _${exportName} = (function () {`);
  out.push(code);
  out.push(`  })(); }`);
  out.push(`  return _${exportName}(_ctx, _cache);`);
  out.push('};');
  out.push('');
}

fs.writeFileSync(OUT, out.join('\n'), 'utf8');
console.log('wrote', OUT, 'with', Object.keys(idToName).length, 'render functions');
